const assert = require('node:assert/strict')
const { createRequire } = require('node:module')
const { buildSync } = createRequire(require.resolve('vite/package.json'))('esbuild')
const { performance } = require('node:perf_hooks')
const output = buildSync({ bundle:true, write:false, platform:'node', format:'cjs', define:{'import.meta.env.BASE_URL':'"/Polyhedron/"'}, stdin:{ resolveDir:process.cwd(), loader:'ts', contents:"export * from './pwa/src/utils/workspace';export * from './pwa/src/utils/translateSearch';export * from './pwa/src/utils/replace';export * from './pwa/src/utils/highlight';" } }).outputFiles[0].text
const wrapped = { exports:{} }; new Function('module','exports','require',output)(wrapped, wrapped.exports, require)
const { defaultSearch, matcher, filterTranslations, replacementChanges, indexWorkspace, updateProject, matchRanges } = wrapped.exports
const options = { ...defaultSearch, filter:'all', sort:'default' }
assert(matcher({...defaultSearch,query:'cat'} )('Cat cats'))
assert(!matcher({...defaultSearch,query:'cat',matchCase:true})('Cat'))
assert(matcher({...defaultSearch,query:'cat',wholeWord:true})('a cat!'))
assert(!matcher({...defaultSearch,query:'cat',wholeWord:true})('cats'))
assert(!matcher({...defaultSearch,query:'cat',wholeWord:true})('caté'))
assert(matcher({...defaultSearch,query:'catel'})('Cățel'))
assert(matcher({...defaultSearch,query:'Cățel',exact:true})('Catel'))
assert(!matcher({...defaultSearch,query:'cat',startsWith:true})('A cat'))
assert.deepEqual(matchRanges('Cățelul merge acasă', {...defaultSearch,query:'catel'}), [[0,5]])
assert.deepEqual(matchRanges('Cat cats CAT', {...defaultSearch,query:'cat',wholeWord:true}), [[0,3],[9,12]])
assert.deepEqual(matchRanges('CATS', {...defaultSearch,query:'cat',matchCase:true}), [])
const entry = (uid,source,target='',needsReview=false) => ({uid,source,target,needsReview,matchType:'none'})
const entries=[entry('1','cat','cat cats CAT'),entry('2','cat','Cățel',true),entry('3','<LSTag>long</LSTag>'),entry('4','%%% note'),entry('5','dog')]
assert.equal(filterTranslations(entries,options).total,4)
assert.equal(filterTranslations(entries,options).translated,2)
assert.deepEqual(filterTranslations(entries,{...options,filter:'needs-review'}).indices,[1])
assert.deepEqual(filterTranslations(entries,{...options,query:'cat',scope:'source',wholeWord:true}).indices,[0,1])
assert.deepEqual(filterTranslations(entries,{...options,sort:'repeated-desc'}).indices.slice(0,2),[0,1])
assert.deepEqual(filterTranslations(entries,{...options,sort:'length-desc'}).indices[0],2)
const changes=replacementChanges(entries,[0,1],'cat','$&',false,true,false)
assert.equal(changes.get('1').target,'$& cats $&','Replacement is literal, not regex syntax')
assert.equal(replacementChanges(entries,[0,1],'cat','dog',true,true,true).get('1').target,'dog cats CAT')
assert.equal(replacementChanges(entries,[0,1],'','dog',false,false,false).size,0)
const first={id:'first',entries}; const second={id:'second',entries:entries.map(row=>({...row,target:'KEEP'}))}
const document={version:1,sessions:[first,second]}
const before=indexWorkspace(first); const updated=updateProject(document,'first',new Map([['1',{target:'changed'}]]))
const after=indexWorkspace(updated.sessions[0])
assert.equal(updated.sessions[1],second,'Other projects are untouched')
assert.equal(updated.sessions[1].entries[0].target,'KEEP')
assert.equal(before.bySource,after.bySource,'Target edits reuse source index')
assert.equal(before.rows,after.rows,'Target edits do not rebuild dialogue topology')
assert.equal(after.byUid.get('1').target,'changed')
const large=Array.from({length:100000},(_,i)=>entry('u'+i,'Source string '+i,i%2?'Traducere '+i:''))
const start=performance.now(); const result=filterTranslations(large,{...options,query:'9999'}); const elapsed=performance.now()-start
assert.equal(result.total,100000); assert.equal(result.indices.length,19)
console.log('PASS: case, whole words, diacritics, scopes, filters, sorting, literal replace, project isolation and source-index reuse')
console.log('100,000 strings: search + counts '+elapsed.toFixed(1)+' ms (synthetic benchmark; production runs in a worker)')
